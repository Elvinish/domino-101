export const BOT_PERSONAS: readonly BotPersona[] = Object.freeze(
  (
    [
      ['male', maleNames],
      ['female', femaleNames],
    ] as const
  ).flatMap(([gender, names]) =>
    names.map((displayName) =>
      Object.freeze({
        displayName,
        gender,
        playerType: 'bot' as const,
      }),
    ),
  ),
);
const byName = new Map(
  BOT_PERSONAS.map((persona) => [persona.displayName, persona]),
);
/** Only call for kind=bot. Unknown/legacy names have no invented gender. */
export function findBotPersona(displayName: string): BotPersona | undefined {
  return byName.get(displayName);
}
